"""Formal KPI definitions.

This catalogue is the reference served by ``GET /api/v1/kpi-catalog`` and shown on the
Methodology page. docs/KPI_CATALOG.md documents the same KPIs; a test keeps both aligned.
"""

from __future__ import annotations

from backend.app.schemas import KpiDefinition

_GLOBAL_FILTERS = "Period, business unit"
_SALES_FILTERS = "Period, business unit, category, product"

KPI_CATALOG: tuple[KpiDefinition, ...] = (
    KpiDefinition(
        id="net_revenue",
        name="Net revenue",
        formula="SUM(fact_sales.net_sales_amount), where net = gross sales - discounts",
        unit="USD",
        grain="Additive across day x business unit x product; reported by month",
        filters=_SALES_FILTERS,
        null_handling="The column is NOT NULL. A slice without sales reports 0.",
        interpretation="Sales actually invoiced after discounts. Higher is better.",
        limitations="No returns, taxes or rebates are modelled.",
    ),
    KpiDefinition(
        id="direct_costs",
        name="Direct costs (COGS)",
        formula="SUM(fact_sales.cogs_amount)",
        unit="USD",
        grain="Additive across day x business unit x product; reported by month",
        filters=_SALES_FILTERS,
        null_handling="The column is NOT NULL. A slice without sales reports 0.",
        interpretation="Cost of the merchandise sold. Lower is better for a given revenue.",
        limitations="Unit cost at the time of sale; no inventory valuation effects.",
    ),
    KpiDefinition(
        id="gross_profit",
        name="Gross profit",
        formula="net_revenue - direct_costs",
        unit="USD",
        grain="Additive; derived from the sales fact",
        filters=_SALES_FILTERS,
        null_handling="Always defined (difference of two sums).",
        interpretation="What remains of revenue after the cost of the goods. Higher is better.",
        limitations="Excludes every operating expense.",
    ),
    KpiDefinition(
        id="gross_margin",
        name="Gross margin",
        formula="gross_profit / net_revenue",
        unit="% (ratio)",
        grain="Non-additive: always computed as a ratio of sums for the selected slice",
        filters=_SALES_FILTERS,
        null_handling="Null when net revenue is 0.",
        interpretation="Share of each revenue dollar kept after direct costs. Higher is better.",
        limitations="Never average margins of sub-slices; changes mix price, cost and mix effects.",
    ),
    KpiDefinition(
        id="operating_expenses",
        name="Operating expenses",
        formula="SUM(fact_operating_expenses.amount)",
        unit="USD",
        grain="Additive across ledger entry; reported by month",
        filters="Period, business unit, cost centre, account",
        null_handling="The column is NOT NULL and > 0. A slice without entries reports 0.",
        interpretation="Cost of running the business excluding the goods sold. Lower is better.",
        limitations="Cannot be split by product or category (no such dimension in the ledger).",
    ),
    KpiDefinition(
        id="operating_income",
        name="Operating income",
        formula="gross_profit - operating_expenses",
        unit="USD",
        grain="Derived by drill-across: both facts are aggregated to month x business unit first",
        filters=_GLOBAL_FILTERS,
        null_handling="Always defined.",
        interpretation="Profit from operations before interest and taxes. Higher is better.",
        limitations="Only by period and business unit; includes depreciation (comparable to EBIT).",
    ),
    KpiDefinition(
        id="operating_margin",
        name="Operating margin",
        formula="operating_income / net_revenue",
        unit="% (ratio)",
        grain="Non-additive: ratio of sums for the selected slice",
        filters=_GLOBAL_FILTERS,
        null_handling="Null when net revenue is 0.",
        interpretation="Operating profit per revenue dollar. Higher is better.",
        limitations="Only by period and business unit.",
    ),
    KpiDefinition(
        id="budget",
        name="Budget",
        formula="SUM(fact_budget.budget_amount) for the accounts of the measure",
        unit="USD",
        grain="Additive across month x business unit x account, within one account type",
        filters="Period (whole months), business unit, account",
        null_handling="The budget grid is complete by a blocking data-quality rule.",
        interpretation="The approved plan for the period.",
        limitations="Single approved version; no forecasts. Not planned by product or cost centre.",
    ),
    KpiDefinition(
        id="actual",
        name="Actual (execution)",
        formula=(
            "vw_actual_by_account_month: net sales -> account 4000, COGS -> account 5000, "
            "operating expenses -> their 6xxx account"
        ),
        unit="USD",
        grain="Month x business unit x account (the grain of the budget)",
        filters="Period (whole months), business unit, account",
        null_handling="A cell without transactions is treated as 0.",
        interpretation="What was actually sold or spent, at the grain of the budget.",
        limitations="The account mapping of sales is fixed in the view definition.",
    ),
    KpiDefinition(
        id="budget_variance",
        name="Budget variance (absolute)",
        formula="actual - budget",
        unit="USD",
        grain="Additive within one account type",
        filters="Period, business unit, account",
        null_handling="Always defined.",
        interpretation=(
            "Favorable when it improves profit: positive for revenue and profit lines, "
            "negative for cost lines. Reported as 'on target' when below 0.5% of budget."
        ),
        limitations="Does not separate volume-driven from rate-driven cost variances.",
    ),
    KpiDefinition(
        id="budget_variance_pct",
        name="Budget variance (%)",
        formula="(actual - budget) / |budget|",
        unit="% (ratio)",
        grain="Non-additive: ratio of sums for the selected slice",
        filters="Period, business unit, account",
        null_handling="Null when the budget is 0.",
        interpretation="Size of the variance relative to the plan.",
        limitations="Unstable for very small budgets; read together with the absolute variance.",
    ),
    KpiDefinition(
        id="mom_growth",
        name="Month-over-month growth",
        formula="(value[m] - value[m-1]) / |value[m-1]|",
        unit="% (ratio)",
        grain="Month",
        filters=_GLOBAL_FILTERS,
        null_handling="Null for the first month of the history or when the previous value is 0.",
        interpretation="Short-term momentum.",
        limitations="Not seasonally adjusted: reflects the calendar as much as performance.",
    ),
    KpiDefinition(
        id="yoy_growth",
        name="Year-over-year growth",
        formula="(value[m] - value[m-12]) / |value[m-12]|",
        unit="% (ratio)",
        grain="Month, or any period compared with the same months one year earlier",
        filters=_GLOBAL_FILTERS,
        null_handling="Null for the first 12 months of the history or when the base is 0.",
        interpretation="Growth net of seasonality.",
        limitations="Available from the second year of data only (2024 onwards).",
    ),
    KpiDefinition(
        id="discount_rate",
        name="Discount rate",
        formula="SUM(discount_amount) / SUM(gross_sales_amount)",
        unit="% (ratio)",
        grain="Non-additive: ratio of sums for the selected slice",
        filters=_SALES_FILTERS,
        null_handling="Null when gross sales are 0.",
        interpretation="Share of list-price sales given away as discounts. Lower is better.",
        limitations="Does not distinguish promotional from negotiated discounts.",
    ),
    KpiDefinition(
        id="revenue_share",
        name="Revenue share",
        formula="net_revenue of the segment / net_revenue of all segments in the selection",
        unit="% (ratio)",
        grain="Segment within the current filters",
        filters=_SALES_FILTERS,
        null_handling="Null when total net revenue is 0.",
        interpretation="Weight of a business unit, category or product in total sales.",
        limitations="Relative to the filtered total, not to the whole company.",
    ),
    KpiDefinition(
        id="expense_ratio",
        name="Expense-to-revenue ratio",
        formula="operating_expenses / net_revenue",
        unit="% (ratio)",
        grain="Non-additive: ratio of sums for the selected slice",
        filters=_GLOBAL_FILTERS,
        null_handling="Null when net revenue is 0.",
        interpretation="Operating cost of generating one revenue dollar. Lower is better.",
        limitations="Fixed costs make it fall mechanically when revenue grows.",
    ),
)
